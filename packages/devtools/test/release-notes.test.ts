// Release body = curated CHANGELOG.md section, never raw git-cliff output: v0.14.0's listed unshipped features
// and todo noise. Lives here, like release-receipt.test.ts, because scripts/ has no vitest project of its own.
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {describe, expect, it} from 'vitest';
// @ts-expect-error untyped .mjs
import {releaseNotes} from '../../../scripts/release/release-notes.mjs';
// @ts-expect-error untyped .mjs
import {lookup} from '../../../scripts/lib/devx-registry.mjs';

const REPO_ROOT = path.resolve(__dirname, '../../..');
const read = (rel: string): string => readFileSync(path.join(REPO_ROOT, rel), 'utf8');
const notes = releaseNotes as (changelog: string, version: string) => string;

const CHANGELOG = `# Changelog

Header prose.

## [0.2.0] - 2026-02-01

Hand-written intro.

### Features

- **core:** a feature

## [0.1.0] - 2026-01-01

First release.

<!-- Generated by git-cliff -->
`;

describe('releaseNotes', () => {
  it('prints the section body up to the next release heading', () => {
    expect(notes(CHANGELOG, '0.2.0')).toBe('Hand-written intro.\n\n### Features\n\n- **core:** a feature\n');
  });

  it('stops the oldest section at the file footer', () => {
    expect(notes(CHANGELOG, '0.1.0')).toBe('First release.\n');
  });

  it('takes the tag form too', () => {
    expect(notes(CHANGELOG, 'v0.2.0')).toBe(notes(CHANGELOG, '0.2.0'));
  });

  it('never matches a version that is only a prefix of a heading', () => {
    expect(() => notes(CHANGELOG, '0.2')).toThrow('CHANGELOG.md has no "## [0.2]" section');
  });

  it('fails loud on a missing section', () => {
    expect(() => notes(CHANGELOG, '9.9.9')).toThrow('CHANGELOG.md has no "## [9.9.9]" section');
  });

  it('fails loud on an empty section', () => {
    expect(() => notes('## [0.3.0] - 2026-03-01\n\n## [0.2.0]\n\nx\n', '0.3.0')).toThrow('"## [0.3.0]" section is empty');
  });

  it('reads every release of the real CHANGELOG.md as one non-empty section', () => {
    const changelog = read('CHANGELOG.md');
    const versions = [...changelog.matchAll(/^## \[([^\]]+)\]/gm)].map((match) => match[1]);
    expect(versions.length).toBeGreaterThan(0);
    for (const version of versions) {
      const body = notes(changelog, version);
      expect(body.trim()).not.toBe('');
      expect(body).not.toMatch(/^## \[/m);
      expect(body).not.toContain('<!-- Generated by git-cliff -->');
    }
  });
});

describe('the release workflows use the curated notes', () => {
  const publish = read('.github/workflows/publish.yml');
  const NOTES_STEP = 'run: node scripts/miondevx.mjs release notes "${VERSION}" > RELEASE_NOTES.md';

  it('publish.yml writes the notes before staging, so a missing section stages nothing', () => {
    expect(publish).toContain(NOTES_STEP);
    expect(publish.indexOf(NOTES_STEP)).toBeLessThan(publish.indexOf('node scripts/miondevx.mjs release tarballs'));
  });

  it('publish.yml publishes the Release (no draft) with those notes, and never runs git-cliff', () => {
    expect(publish).toContain('gh release create "v${VERSION}" --title "v${VERSION}" --notes-file RELEASE_NOTES.md');
    expect(publish).not.toContain('--draft');
    expect(publish).not.toMatch(/git-cliff/i);
  });

  it("pre-publish.yml's version-fresh job checks the section on the release PR", () => {
    const prePublish = read('.github/workflows/pre-publish.yml');
    const job = prePublish.slice(prePublish.indexOf('  version-fresh:'), prePublish.indexOf('  main-ancestor:'));
    expect(job).toContain('run: node scripts/miondevx.mjs release notes "$(jq -r .version version.json)" >/dev/null');
  });

  it('`release notes` is on the CLI table and needs no engine build', () => {
    expect(lookup('release', 'notes')).toMatchObject({args: '<version>', build: false});
  });
});
