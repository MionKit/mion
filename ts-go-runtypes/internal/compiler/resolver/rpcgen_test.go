// TestRpc_NoRouterInitWritesNoRpc: a program with batches but no router (a
// client project) has nothing to serve the table to, so no rpc/ is written
// and one left behind by an earlier server build is removed.
func TestRpc_NoRouterInitWritesNoRpc(t *testing.T) {
	outDir := t.TempDir()
	generate(t, setupGen(t, rpcSources(), outDir))
	if _, err := os.Stat(filepath.Join(outDir, "rpc")); err != nil {
		t.Fatalf("rpc/ expected after the server generate: %v", err)
	}
	clientOnly := rpcSources()
	delete(clientOnly, "server.ts")
	gen := generate(t, setupGen(t, clientOnly, outDir))
	if gen.BatchesModule != "" || len(gen.RouterInitFiles) != 0 {
		t.Errorf("a client-only program must echo no module and no router-init files, got %q / %v", gen.BatchesModule, gen.RouterInitFiles)
	}
	if _, err := os.Stat(filepath.Join(outDir, "rpc")); !os.IsNotExist(err) {
		t.Errorf("rpc/ must not exist for a program that creates no router (stat err = %v)", err)
	}
	// the client half still gets its ids and hashes: that is the transform's job, not the table's
	if code := transform(t, setupGen(t, clientOnly, t.TempDir()), "a.ts"); !strings.Contains(code, "'b_") || !strings.Contains(code, "'rt::") {
		t.Errorf("client transform lost the batch id or the mapper hash:\n%s", code)
	}
}

// TestRpc_StaleMapperPruned: a mapper that is no longer referenced is deleted
// on the next generate; the table imports only the current one.
func TestRpc_StaleMapperPruned(t *testing.T) {
	outDir := t.TempDir()
	generate(t, setupGen(t, rpcSources(), outDir))
	before := readTree(t, filepath.Join(outDir, "rpc"))
	var oldMapper string
	for path := range before {
		if strings.HasPrefix(path, "pf/rt/") {
			oldMapper = path
		}
	}
	if oldMapper == "" {
		t.Fatalf("no mapper module written: %v", before)
	}

	changed := rpcSources()
	changed["a.ts"] = strings.Replace(batchSources["a.ts"], "(u: {id: number}) => u.id", "(u: {name: string}) => u.name.length", 1)
	generate(t, setupGen(t, changed, outDir))
	after := readTree(t, filepath.Join(outDir, "rpc"))
	if _, stale := after[oldMapper]; stale {
		t.Errorf("stale mapper %s survived the regenerate", oldMapper)
	}
	var mappers []string
	for path := range after {
		if strings.HasPrefix(path, "pf/rt/") {
			mappers = append(mappers, path)
		}
	}
	if len(mappers) != 1 || !strings.Contains(after[mappers[0]], "u.name.length") {
		t.Errorf("expected exactly the new mapper, got %v", mappers)
	}
	if imports := mapperImportRE.FindAllStringSubmatch(after["batches.generated.js"], -1); len(imports) != 1 || "./"+mappers[0] != imports[0][2] {
		t.Errorf("table imports %v, want ./%s", imports, mappers[0])
	}
}

// TestRpc_DeterministicAndWriteOnChange: the same programs yield a
// byte-identical rpc/ tree across sessions, and an unchanged tree is never
// rewritten (mtimes stay put).
func TestRpc_DeterministicAndWriteOnChange(t *testing.T) {
	outDir := t.TempDir()
	r := setupGen(t, rpcSources(), outDir)
	generate(t, r)
	rpcDir := filepath.Join(outDir, "rpc")
	first := readTree(t, rpcDir)
	if len(first) < 2 {
		t.Fatalf("expected the table and a mapper, got %v", first)
	}
	mtimes := map[string]time.Time{}
	for path := range first {
		info, err := os.Stat(filepath.Join(rpcDir, filepath.FromSlash(path)))
		if err != nil {
			t.Fatal(err)
		}
		mtimes[path] = info.ModTime()
	}
	// a rewrite would need a later mtime, so make the clock observable
	time.Sleep(20 * time.Millisecond)
	generate(t, r)
	for path, stamp := range mtimes {
		info, err := os.Stat(filepath.Join(rpcDir, filepath.FromSlash(path)))
		if err != nil {
			t.Fatal(err)
		}
		if !info.ModTime().Equal(stamp) {
			t.Errorf("%s was rewritten although nothing changed", path)
		}
	}

	otherDir := t.TempDir()
	generate(t, setupGen(t, rpcSources(), otherDir))
	second := readTree(t, filepath.Join(otherDir, "rpc"))
	if len(second) != len(first) {
		t.Fatalf("tree sizes differ: %d vs %d", len(first), len(second))
	}
	for path, content := range first {
		if second[path] != content {
			t.Errorf("%s differs between two sessions over the same program", path)
		}
	}
}

// TestRpc_ClientTsconfigSeparateProject: the server session reads the batch
// source from a SEPARATE client project on disk, echoes that project's files
// for the dev watcher, rebuilds it when one of them changes, and names a bad
// tsconfig in its error.
func TestRpc_ClientTsconfigSeparateProject(t *testing.T) {
	clientDir := writeClientProject(t)
	outDir := t.TempDir()
	server := setupInlineWith(t, map[string]string{"router.d.ts": routerDTS, "server.ts": serverTS}, func(programOpts *program.Options, resolverOpts *resolver.Options) {
		programOpts.SingleThreaded = true
		resolverOpts.SingleThreaded = true
		resolverOpts.GenDir = outDir
		resolverOpts.TransformRelative = true
		resolverOpts.ClientTsconfig = filepath.Join(clientDir, "tsconfig.json")
	})
	gen := generate(t, server)
	if gen.BatchesModule == "" {
		t.Fatalf("no batch module generated from the client project; diagnostics: %+v", gen.Diagnostics)
	}
	module := readRpcModule(t, outDir)
	if ids := batchIdRE.FindAllString(module, -1); len(ids) != 1 {
		t.Errorf("expected the client's one batch, got %v:\n%s", ids, module)
	}
	if !mapperImportRE.MatchString(module) {
		t.Errorf("the client's inline mapper must be imported:\n%s", module)
	}
	if strings.Contains(module, clientDir) {
		t.Errorf("the module leaks the client project path:\n%s", module)
	}
	clientA := filepath.Join(clientDir, "src", "a.ts")
	if len(gen.BatchSourceFiles) != 1 || gen.BatchSourceFiles[0] != clientA {
		t.Errorf("BatchSourceFiles = %v, want [%s]", gen.BatchSourceFiles, clientA)
	}
	if code := transform(t, server, "server.ts"); !strings.Contains(code, "rpc/batches.generated.js';") {
		t.Errorf("server transform lacks the table import:\n%s", code)
	}

	// a client edit is picked up by the next generate (the stamps changed)
	time.Sleep(20 * time.Millisecond)
	writeTestFile(t, clientA, batchSources["a.ts"]+"export const c = batch([routes.orders.list(1)]);\n")
	gen = generate(t, server)
	if ids := batchIdRE.FindAllString(readRpcModule(t, outDir), -1); len(ids) != 2 {
		t.Errorf("expected two batches after the client edit, got %v", ids)
	}

	// a tsconfig that does not exist fails generate and names itself
	broken := setupInlineWith(t, map[string]string{"router.d.ts": routerDTS, "server.ts": serverTS}, func(programOpts *program.Options, resolverOpts *resolver.Options) {
		programOpts.SingleThreaded = true
		resolverOpts.SingleThreaded = true
		resolverOpts.GenDir = t.TempDir()
		resolverOpts.ClientTsconfig = filepath.Join(clientDir, "missing.json")
	})
	if resp := broken.Dispatch(protocol.Request{Op: protocol.OpGenerate}); resp.Error == "" || !strings.Contains(resp.Error, "missing.json") {
		t.Errorf("expected a generate error naming missing.json, got %q", resp.Error)
	}
}

// writeClientProject writes a real client project to disk: a tsconfig over
// src/, the batches fixtures, and the real marker package under node_modules
// so the brands resolve exactly as they do in a consumer.
func writeClientProject(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	writeTestFile(t, filepath.Join(dir, "tsconfig.json"), `{
  "compilerOptions": {
    "target": "ES2022", "module": "ESNext", "moduleResolution": "Bundler",
    "rootDir": "src", "noEmit": true, "strict": true, "allowImportingTsExtensions": true
  },
  "include": ["src"]
}
`)
	for rel, content := range realMarkerOverlay(t) {
		writeTestFile(t, filepath.Join(dir, filepath.FromSlash(rel)), content)
	}
	writeTestFile(t, filepath.Join(dir, "src", "client.d.ts"), batchClientDTS)
	writeTestFile(t, filepath.Join(dir, "src", "routes.ts"), batchRoutesTS)
	writeTestFile(t, filepath.Join(dir, "src", "a.ts"), batchSources["a.ts"])
	return dir
}

func writeTestFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func containsString(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}
