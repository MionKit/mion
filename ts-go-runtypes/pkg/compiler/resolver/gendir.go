package resolver

import (
	"strings"

	"github.com/mionkit/mion/ts-go-runtypes/pkg/constants"
)

// GenDirEntry is one member of the generated output root: a subdir or a file the build owns there.
type GenDirEntry struct {
	Name string
	// Dir entries must be real directories; a plain file by that name fails the output-dir guard.
	Dir bool
	// Bullet is its line(s) in the genDir README, in registration order; empty adds none.
	Bullet string
	// Readme is a Dir entry's own README, written with its folder if absent; empty writes neither.
	Readme  string
	Owner   string // "" for mion, else the extension name (cli.Main sets it)
	Replace bool
}

var genDirTable = NewRegistry[GenDirEntry]("genDir entry")

// RegisterGenDirEntry adds a member the output-dir guard accepts and the genDir README lists.
func RegisterGenDirEntry(entry GenDirEntry) {
	genDirTable.Add(entry.Name, entry, entry.Replace)
}

// genDirReadmeHeader opens the genDir README; the entries' bullets follow.
const genDirReadmeHeader = "# RunTypes output\n" +
	"\n" +
	"This folder is managed by RunTypes (the `genDir` option, set in tsconfig\n" +
	"or on the bundler plugin). Everything under it follows convention:\n" +
	"\n"

func genDirReadme() string {
	var builder strings.Builder
	builder.WriteString(genDirReadmeHeader)
	for _, entry := range genDirTable.List() {
		builder.WriteString(entry.Bullet)
	}
	return builder.String()
}

// extensionGenDirMembers names the extension-owned members for the output-dir refusal, "" when there are none.
func extensionGenDirMembers() string {
	var names []string
	for _, entry := range genDirTable.List() {
		if entry.Owner == "" {
			continue
		}
		name := "`" + entry.Name + "`"
		if entry.Dir {
			name = "`" + entry.Name + "/`"
		}
		names = append(names, name+" ("+entry.Owner+")")
	}
	if len(names) == 0 {
		return ""
	}
	return ", the extension members " + strings.Join(names, ", ")
}

// mion's own members, registered at package init so every init() row (the `enriched` row in enrich_op.go, an
// extension's) lands after them.
var _ = registerBuiltinGenDirEntries()

func registerBuiltinGenDirEntries() bool {
	for _, entry := range []GenDirEntry{
		{Name: typesSubdir, Dir: true,
			Bullet: "- `types/`, `api/`, `rpc/` — modules generated on every build. Not committed; do not edit.\n",
			Readme: "# Generated modules\n" +
				"\n" +
				"Everything here is regenerated by RunTypes on every build.\n" +
				"Do not edit; nothing in this folder is committed (see .gitignore).\n"},
		// The batch table + its mapper modules.
		{Name: constants.RpcModuleDir, Dir: true},
		// What a bundling client build bundles (see apigen.go).
		{Name: constants.ApiModuleDir, Dir: true},
		{Name: "README.md"},
		{Name: ".gitignore"},
		{Name: ".gitkeep"},
	} {
		RegisterGenDirEntry(entry)
	}
	return true
}
