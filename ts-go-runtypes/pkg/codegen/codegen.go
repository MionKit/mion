// Package codegen holds the helpers the Go→TS generators share (cmd/gen-*). Codegen is not runtime: a generator
// built on mion is its own command that uses these, never a row mion's own commands write.
package codegen

import (
	"os"
	"path/filepath"
)

// RepoRoot is the nearest ancestor holding package.json, so an output path resolves the same from the repo root or
// the Go module dir (`go -C ts-go-runtypes run ...`); "." when none is found.
func RepoRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		return "."
	}
	for {
		if _, statErr := os.Stat(filepath.Join(dir, "package.json")); statErr == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "."
		}
		dir = parent
	}
}

// Header is the banner every generated TS file opens with.
func Header(tool, source, regen string) string {
	return "// Code generated by " + tool + ". DO NOT EDIT.\n" +
		"// Source: " + source + ".\n" +
		"// Regenerate via `" + regen + "` after changing the Go source.\n"
}
