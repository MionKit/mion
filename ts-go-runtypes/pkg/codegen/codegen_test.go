package codegen

import (
	"os"
	"path/filepath"
	"testing"
)

func TestHeader(t *testing.T) {
	want := "// Code generated by cmd/gen-x. DO NOT EDIT.\n// Source: pkg/x/x.go.\n// Regenerate via `pnpm x` after changing the Go source.\n"
	if got := Header("cmd/gen-x", "pkg/x/x.go", "pnpm x"); got != want {
		t.Fatalf("Header = %q", got)
	}
}

func TestRepoRoot_FindsThePackageJson(t *testing.T) {
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "package.json"), []byte("{}"), 0o644); err != nil {
		t.Fatal(err)
	}
	nested := filepath.Join(root, "a", "b")
	if err := os.MkdirAll(nested, 0o755); err != nil {
		t.Fatal(err)
	}
	t.Chdir(nested)
	if got := RepoRoot(); got != root {
		t.Fatalf("RepoRoot = %q, want %q", got, root)
	}
}
