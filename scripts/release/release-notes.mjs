// Prints one version's curated CHANGELOG.md section, the GitHub Release body in publish.yml. A missing or
// empty section fails the run: it means the bump PR skipped the changelog. Must stay zero-dep: the publish
// job runs it pnpm-free, as `node scripts/miondevx.mjs release notes <version>`.

import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {REPO_ROOT} from '../lib/env.mjs';
import {die, reportCliError} from '../lib/proc.mjs';

const HEADING = '## [';
// cliff.toml's footer, below the oldest release.
const FOOTER = '<!-- Generated by git-cliff -->';

// A line that starts its own Markdown block instead of continuing the one above.
const BLOCK_START = /^\s*(#|[-*+] |\d+[.)] |>|\||```)/;
const FENCE = /^\s*```/;

// GitHub renders a Release body's single newlines as hard breaks; blank lines and fenced code stay as they are.
export function unwrap(markdown) {
  const out = [];
  let inFence = false;
  for (const line of markdown.split('\n')) {
    const prev = out.at(-1);
    const continues = !inFence && prev?.trim() && line.trim() && !BLOCK_START.test(line) && !/^\s*(#|\||```)/.test(prev);
    if (continues) out[out.length - 1] = `${prev} ${line.trim()}`;
    else out.push(line);
    if (FENCE.test(line)) inFence = !inFence;
  }
  return out.join('\n');
}

// Throws a CliError (via die) when the section is absent or empty.
export function releaseNotes(changelog, tagOrVersion) {
  const version = tagOrVersion.replace(/^v/, '');
  const lines = changelog.split('\n');
  const start = lines.findIndex((line) => line.startsWith(`${HEADING}${version}]`));
  if (start === -1) die(`release notes: CHANGELOG.md has no "${HEADING}${version}]" section. Add it in the bump PR (release-to-prod skill, bump.md).`);
  const next = lines.findIndex((line, at) => at > start && (line.startsWith(HEADING) || line === FOOTER));
  const body = lines
    .slice(start + 1, next === -1 ? undefined : next)
    .join('\n')
    .trim();
  if (!body) die(`release notes: the CHANGELOG.md "${HEADING}${version}]" section is empty.`);
  return `${unwrap(body)}\n`;
}

function main([version, ...extra]) {
  if (!version || extra.length > 0) die('usage: miondevx release notes <version>', 2);
  process.stdout.write(releaseNotes(readFileSync(join(REPO_ROOT, 'CHANGELOG.md'), 'utf8'), version));
}

if (import.meta.main) {
  try {
    main(process.argv.slice(2));
  } catch (err) {
    reportCliError(err);
  }
}
