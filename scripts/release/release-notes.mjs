// Prints one version's curated CHANGELOG.md section, the GitHub Release body in publish.yml. A missing or
// empty section fails the run: it means the bump PR skipped the changelog. Must stay zero-dep: the publish
// job runs it pnpm-free, as `node scripts/miondevx.mjs release notes <version>`.

import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {REPO_ROOT} from '../lib/env.mjs';
import {die, reportCliError} from '../lib/proc.mjs';

const HEADING = '## [';
// cliff.toml's footer, below the oldest release.
const FOOTER = '<!-- Generated by git-cliff -->';

// Only what the changelog uses can be unwrapped safely; anything else fails the run instead of a mangled body.
const UNSUPPORTED = [
  [/^\s*(```|~~~)/, 'a code fence'],
  [/^\s*</, 'an HTML block or comment'],
  [/^\s*[-*_=]{3,}\s*$/, 'a horizontal rule or setext heading underline'],
  [/\S( {2}|\\)$/, 'a hard line break'],
  [/^\s*\[[^\]]+\]:/, 'a link definition'],
  [/^\s*>/, 'a quote'],
  [/^\s*\||^\s*:?-{3,}:?\s*\|/, 'a table row'],
  [/^\s*([-*+]|\d+[.)])(\t|$)/, 'a list marker without a space after it'],
  [/^\s*\+ /, 'a `+` list marker'],
];
const HEADING_LINE = /^ {0,3}#{1,6}(\s|$)/;
const BULLET = /^(\s*)[-*] /;
const ORDERED = /^(\s*)(\d+)[.)]\s/;

// GitHub renders a Release body's single newlines as hard breaks, so each paragraph and list item becomes one line.
// Supports paragraphs, `- ` / `* ` / `N. ` items with continuations and nesting, ATX headings and blank lines.
export function unwrap(markdown, {version = '', firstLine = 1} = {}) {
  const out = [];
  let inList = false;
  let orderedIndent; // indent of the ordered list being continued, so `2.` there is an item, not prose
  markdown.split('\n').forEach((line, at) => {
    const unsupported = UNSUPPORTED.find(([pattern]) => pattern.test(line));
    const where = `CHANGELOG.md line ${firstLine + at}${version ? ` (## [${version}])` : ''}`;
    if (unsupported) die(`release notes: ${where} has ${unsupported[1]}, which the release body cannot carry. Rewrite it as paragraphs or list items.`);
    const prev = out.at(-1);
    const ordered = ORDERED.exec(line);
    const item = BULLET.test(line) || (ordered && (ordered[2] === '1' || ordered[1].length === orderedIndent));
    const continues = Boolean(prev?.trim()) && line.trim() !== '' && !item && !HEADING_LINE.test(line) && !HEADING_LINE.test(prev);
    if (/^ {4,}\S/.test(line) && !(continues && inList)) die(`release notes: ${where} has an indented code block, which the release body cannot carry. Rewrite it as paragraphs or list items.`);
    if (continues) return void (out[out.length - 1] = `${prev} ${line.trim()}`);
    out.push(line);
    if (item) {
      inList = true;
      if (ordered) orderedIndent = ordered[1].length;
    } else if (line.trim() !== '') {
      inList = false;
      orderedIndent = undefined;
    }
  });
  return out.join('\n');
}

// Throws a CliError (via die) when the section is absent, empty, or carries Markdown unwrap cannot keep.
export function releaseNotes(changelog, tagOrVersion) {
  const version = tagOrVersion.replace(/^v/, '');
  const lines = changelog.split('\n');
  const start = lines.findIndex((line) => line.startsWith(`${HEADING}${version}]`));
  if (start === -1) die(`release notes: CHANGELOG.md has no "${HEADING}${version}]" section. Add it in the bump PR (release-to-prod skill, bump.md).`);
  const next = lines.findIndex((line, at) => at > start && (line.startsWith(HEADING) || line === FOOTER));
  const section = lines.slice(start + 1, next === -1 ? undefined : next).join('\n');
  const body = unwrap(section, {version, firstLine: start + 2}).trim();
  if (!body) die(`release notes: the CHANGELOG.md "${HEADING}${version}]" section is empty.`);
  return `${body}\n`;
}

function main([version, ...extra]) {
  if (!version || extra.length > 0) die('usage: miondevx release notes <version>', 2);
  process.stdout.write(releaseNotes(readFileSync(join(REPO_ROOT, 'CHANGELOG.md'), 'utf8'), version));
}

if (import.meta.main) {
  try {
    main(process.argv.slice(2));
  } catch (err) {
    reportCliError(err);
  }
}
