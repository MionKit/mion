// drizzle-translate.mjs — translate drizzle's own suites onto the slim packages
// and typecheck the result, on the HOST. No container, no database.
//
// This is the risky half of the drizzle-e2e lane on its own: the translation.
// Running it here is fast (a few seconds against 17k lines of real drizzle test
// code) and needs nothing but the workspace, so a change to the translator or to
// a recorder's types is checked long before anything pulls a podman image.
//
// `--to-types` converts the translated tree again, onto the pure-type road, and
// typechecks that against the same control. Both translations, no container.
//
// `pnpm miondevx release drizzle-e2e` is the full lane: same translations, then the
// packages installed from verdaccio and the suites run against a real database.
//
// The tree is generated under .cache/drizzle-suites/<tag>-translated/, which is
// gitignored, and removed again unless --keep.
import {execFileSync, spawnSync} from 'node:child_process';
import {cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {ensureDrizzleSuites, readPin, SUITES_CACHE_DIR} from '../drizzle/fetch-suites.mjs';
import {loadEnv, REPO_ROOT} from '../lib/env.mjs';
import {info, note, noteErr, reportCliError, success} from '../lib/proc.mjs';
import {diffTypeErrors, errorLines} from '../../container/drizzle-e2e/shared/baseline.mjs';

const BINARY = path.join(REPO_ROOT, 'bin/mion');

// The mion packages resolve through the workspace SOURCES here, not the packed
// tarballs the container installs. That is the point of the host lane: it checks
// the tree you are editing.
function writeTsconfig(workDir) {
  const paths = {'~/*': ['./tests/*']};
  for (const [specifier, target] of [
    ['@mionjs/drizzle-orm', 'packages/drizzle-orm/src/index.ts'],
    ['@mionjs/drizzle-orm-pg-core', 'packages/drizzle-orm-pg-core/src/index.ts'],
    ['@mionjs/drizzle-orm-pg-core/drizzle', 'packages/drizzle-orm-pg-core/src/drizzle.ts'],
    ['@mionjs/drizzle-orm-mysql-core', 'packages/drizzle-orm-mysql-core/src/index.ts'],
    ['@mionjs/drizzle-orm-mysql-core/drizzle', 'packages/drizzle-orm-mysql-core/src/drizzle.ts'],
    ['@mionjs/drizzle-orm-sqlite-core', 'packages/drizzle-orm-sqlite-core/src/index.ts'],
    ['@mionjs/drizzle-orm-sqlite-core/drizzle', 'packages/drizzle-orm-sqlite-core/src/drizzle.ts'],
  ]) {
    paths[specifier] = [path.relative(workDir, path.join(REPO_ROOT, target))];
  }
  const config = {
    $comment: 'GENERATED by scripts/core/drizzle-translate.mjs. The container lane uses container/drizzle-e2e/shared/tsconfig.json instead, which resolves the packages from verdaccio the way a consumer does.',
    compilerOptions: {
      target: 'ESNext',
      // No lib override, like the container lane's tsconfig: the default
      // ESNext lib is what a consumer compiles on, and sqlite's
      // blob({mode: 'buffer'}) column reflects there.
      module: 'Preserve',
      moduleResolution: 'Bundler',
      strict: true,
      skipLibCheck: true,
      noEmit: true,
      esModuleInterop: true,
      resolveJsonModule: true,
      allowImportingTsExtensions: true,
      // Match the container lane's tsconfig. Without node's types sqlite's
      // `blob({mode: 'buffer'})` resolves to `never` here and nowhere else,
      // which would show up as a translation difference that is really a
      // missing @types/node on this host.
      types: ['node'],
      // The workspace packages publish a `source` export condition; without it
      // @mionjs/run-types resolves to a possibly stale dist.
      customConditions: ['source'],
      paths,
    },
    include: ['tests/**/*.ts'],
  };
  writeFileSync(path.join(workDir, 'tsconfig.json'), `${JSON.stringify(config, null, 2)}\n`);
}

function typecheck(dir) {
  const result = spawnSync('pnpm', ['exec', 'tsc', '--noEmit', '-p', path.join(dir, 'tsconfig.json')], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return errorLines(`${result.stdout ?? ''}${result.stderr ?? ''}`);
}

export async function main(args) {
  // Reached through the miondevx gate, which builds the engine first; this only
  // catches a direct `node scripts/core/drizzle-translate.mjs` on a cold tree.
  if (!existsSync(BINARY)) {
    noteErr('drizzle-translate: bin/mion is missing — run `pnpm miondevx core build` first.');
    process.exitCode = 1;
    return;
  }
  const suitesDir = await ensureDrizzleSuites();
  const pin = readPin();
  const workDir = path.join(SUITES_CACHE_DIR, `${pin.tag}-translated`);
  rmSync(workDir, {recursive: true, force: true});
  mkdirSync(workDir, {recursive: true});
  cpSync(path.join(suitesDir, 'tests'), path.join(workDir, 'tests'), {recursive: true});
  writeTsconfig(workDir);
  // The CONTROL: the same tree, never translated. It is what turns "this error
  // is drizzle's own" from a claim into a measurement.
  const controlDir = path.join(SUITES_CACHE_DIR, `${pin.tag}-control`);
  rmSync(controlDir, {recursive: true, force: true});
  mkdirSync(controlDir, {recursive: true});
  cpSync(path.join(suitesDir, 'tests'), path.join(controlDir, 'tests'), {recursive: true});
  writeTsconfig(controlDir);

  info(`translating the ${pin.tag} suites onto the slim packages`);
  const reportFile = path.join(workDir, 'report.json');
  const translate = spawnSync(BINARY, ['drizzle-migrate', '--tsconfig', path.join(workDir, 'tsconfig.json'), '--report', reportFile, path.join(workDir, 'tests')], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (translate.error) throw translate.error;
  process.stdout.write(translate.stdout ?? '');
  const report = JSON.parse(readFileSync(reportFile, 'utf8'));
  // Refusals are EXPECTED and named: a refused declaration stays valid drizzle,
  // so its test still runs. Only a change in what they are matters.
  const byCode = {};
  for (const refusal of report.refusals ?? []) byCode[refusal.code] = (byCode[refusal.code] ?? 0) + 1;
  note(`refusals: ${JSON.stringify(byCode)}`);
  note(`rewrote: ${Object.entries(report.used ?? {}).map(([dialect, names]) => `${dialect} ${names.length}`).join(', ')}`);

  info('typechecking the translated tree against the untranslated control');
  const errors = typecheck(workDir);
  const controlErrors = typecheck(controlDir);
  const {added, removed} = diffTypeErrors({
    translated: errors,
    control: controlErrors,
    // tsc prints paths relative to its cwd, so strip both spellings of each root.
    roots: [`${workDir}/`, `${controlDir}/`, `${path.relative(REPO_ROOT, workDir)}/`, `${path.relative(REPO_ROOT, controlDir)}/`],
  });
  note(`type errors: ${controlErrors.length} before the translation, ${errors.length} after`);
  if (added.length > 0) {
    noteErr(`drizzle-translate: the translation ADDED ${added.length} type error(s) the untranslated tree does not have:`);
    noteErr(added.slice(0, 40).join('\n'));
    process.exitCode = 1;
  }
  if (removed.length > 0) {
    noteErr(`drizzle-translate: the translation REMOVED ${removed.length} type error(s), so the two trees are no longer the same program:`);
    noteErr(removed.slice(0, 40).join('\n'));
    process.exitCode = 1;
  }
  // The SECOND translation, off by default because it doubles the run: the
  // translated tree converted again onto the pure-type road, typechecked
  // against the SAME control. The container lane runs the converted tree
  // against a real database; this is the few-second half of it.
  let typesDir = '';
  if (args.includes('--to-types')) {
    typesDir = path.join(SUITES_CACHE_DIR, `${pin.tag}-types`);
    rmSync(typesDir, {recursive: true, force: true});
    cpSync(workDir, typesDir, {recursive: true});
    writeTsconfig(typesDir);
    info('converting the translated tree onto the type road');
    const convertReport = path.join(typesDir, 'convert-report.json');
    const converted = spawnSync(
      BINARY,
      ['convert', '--tsconfig', path.join(typesDir, 'tsconfig.json'), '--to', 'type', '--report', convertReport, path.join(typesDir, 'tests')],
      {cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024}
    );
    if (converted.error) throw converted.error;
    process.stdout.write(converted.stdout ?? '');
    const report = JSON.parse(readFileSync(convertReport, 'utf8'));
    const convertedCount = (report.files ?? []).reduce((total, file) => total + (file.converted?.length ?? 0), 0);
    note(`converted ${convertedCount} table(s); ${(report.refusals ?? []).length} refusal(s), each with a reason`);
    // A refusal costs COVERAGE, never correctness: the refused declaration stays
    // valid builders code and its test still runs. What must not change is the
    // program, so the bar is the control's, exactly as above.
    const typeErrors = typecheck(typesDir);
    const typeDiff = diffTypeErrors({
      translated: typeErrors,
      control: controlErrors,
      roots: [`${typesDir}/`, `${controlDir}/`, `${path.relative(REPO_ROOT, typesDir)}/`, `${path.relative(REPO_ROOT, controlDir)}/`],
    });
    note(`type errors on the type road: ${controlErrors.length} before, ${typeErrors.length} after`);
    if (typeDiff.added.length > 0) {
      noteErr(`drizzle-translate: the type-road conversion ADDED ${typeDiff.added.length} type error(s) the untranslated tree does not have:`);
      noteErr(typeDiff.added.slice(0, 40).join('\n'));
      process.exitCode = 1;
    }
    if (typeDiff.removed.length > 0) {
      noteErr(`drizzle-translate: the type-road conversion REMOVED ${typeDiff.removed.length} type error(s), so the two trees are no longer the same program:`);
      noteErr(typeDiff.removed.slice(0, 40).join('\n'));
      process.exitCode = 1;
    }
  }

  if (args.includes('--keep')) {
    note(`--keep: left the translated tree in ${path.relative(REPO_ROOT, workDir)} (control: ${path.relative(REPO_ROOT, controlDir)})`);
    if (typesDir) note(`--keep: left the type-road tree in ${path.relative(REPO_ROOT, typesDir)}`);
  } else {
    rmSync(workDir, {recursive: true, force: true});
    rmSync(controlDir, {recursive: true, force: true});
    if (typesDir) rmSync(typesDir, {recursive: true, force: true});
  }
  if (process.exitCode !== 1) success('the drizzle suites translate and typecheck against the slim packages');
}

if (import.meta.main) {
  loadEnv();
  main(process.argv.slice(2)).catch(reportCliError);
}
